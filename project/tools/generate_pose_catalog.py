"""Validate the authored pose CSV and generate its small C lookup table.

Authored rows are also applied to every other player-triggered animation that draws the same
sprites (pose_sprite_groups.csv, from sprite_duplicates.py --write-groups). An explicit row for an
animation always wins; only authored rows are shared, never defaults.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from pathlib import Path


HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import paths  # noqa: E402
GROUPS = paths.DATA / "pose_sprite_groups.csv"
FIELDS = ("har", "animation", "sprite", "side", "flags", "reach", "elbow_y",
          "elbow_z", "wrist_y", "wrist_z", "knee_y", "knee_z", "ankle_y", "ankle_z",
          "knee2_y", "knee2_z", "ankle2_y", "ankle2_z", "body_z", "lean",
          "elbow2_y", "elbow2_z", "wrist2_y", "wrist2_z", "body_y")
FLAG_FIELDS = {
    "reach": ("reach",),
    "arm": ("elbow_y", "elbow_z", "wrist_y", "wrist_z"),
    "leg": ("knee_y", "knee_z", "ankle_y", "ankle_z"),
    "leg2": ("knee2_y", "knee2_z", "ankle2_y", "ankle2_z"),
    "body": ("body_z",),
    "lean": ("lean",),
    "arm2": ("elbow2_y", "elbow2_z", "wrist2_y", "wrist2_z"),
    "drop": ("body_y",),
    "fist": (),
}


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        if tuple(reader.fieldnames or ()) != FIELDS:
            raise ValueError("Pose catalog header does not match the documented schema")
        rows = list(reader)
    seen: set[tuple[int, int, int]] = set()
    for line, row in enumerate(rows, 2):
        if None in row:
            raise ValueError(f"Extra CSV column on line {line}")
        har, animation, sprite, side = (int(row[name]) for name in ("har", "animation", "sprite", "side"))
        if not (0 <= har <= 10 and 0 <= animation <= 255 and 0 <= sprite <= 255 and side in (-1, 1)):
            raise ValueError(f"Invalid HAR, animation, sprite, or side on line {line}")
        key = (har, animation, sprite)
        if key in seen:
            raise ValueError(f"Duplicate pose key {key} on line {line}")
        seen.add(key)
        flags = row["flags"].split("|")
        if len(flags) != len(set(flags)) or not flags or any(flag not in FLAG_FIELDS for flag in flags):
            raise ValueError(f"Invalid flags on line {line}: {row['flags']}")
        required = {field for flag in flags for field in FLAG_FIELDS[flag]}
        for name in FIELDS[5:]:
            value = row[name]
            if name in required:
                if not value or not math.isfinite(float(value)):
                    raise ValueError(f"Missing or nonfinite {name} on line {line}")
            elif value:
                raise ValueError(f"Unused {name} on line {line}; add its flag or clear it")
    return sorted(rows, key=lambda row: tuple(int(row[name]) for name in ("har", "animation", "sprite")))


def expand_shared(rows: list[dict[str, str]], path: Path) -> tuple[list[dict[str, str]], int]:
    """Copy each authored row to the other animations of its sprite group that have no row of their own."""
    if not path.is_file():
        return rows, 0
    have = {(int(r["har"]), int(r["animation"]), int(r["sprite"])): r for r in rows}
    added = 0
    with path.open(newline="", encoding="utf-8") as stream:
        for group in csv.DictReader(stream):
            har, sprites = int(group["har"]), int(group["sprites"])
            members = sorted(int(a) for a in group["animations"].split())
            for sprite in range(sprites):
                source = next((have[(har, a, sprite)] for a in members if (har, a, sprite) in have), None)
                if source is None:
                    continue
                for animation in members:
                    if (har, animation, sprite) not in have:
                        have[(har, animation, sprite)] = {**source, "animation": str(animation)}
                        added += 1
    return sorted(have.values(), key=lambda r: tuple(int(r[n]) for n in ("har", "animation", "sprite"))), added


def render(rows: list[dict[str, str]]) -> str:
    lines = [
        "// Generated by generate_pose_catalog.py from pose_catalog.csv. Do not edit directly.",
        '#include "pose_catalog.h"',
        "",
        "#include <stddef.h>",
        "",
        "static const PoseFrame frames[] = {",
    ]
    for row in rows:
        flags = row["flags"].split("|")
        members = [f".har={row['har']}", f".animation={row['animation']}",
                   f".sprite={row['sprite']}", f".side={row['side']}",
                   ".flags=" + "|".join("POSE_" + flag.upper() for flag in flags)]
        for name in FIELDS[5:]:
            if row[name]:
                members.append(f".{name}={row[name]}f")
        lines.append("    {" + ",".join(members) + "},")
    lines.extend([
        "};",
        "",
        "const PoseFrame *pose_catalog_lookup(int har, int animation, int sprite) {",
        "    size_t low=0, high=sizeof(frames)/sizeof(frames[0]);",
        "    while(low<high) {",
        "        size_t mid=low+(high-low)/2;",
        "        const PoseFrame *frame=&frames[mid];",
        "        if(frame->har<har || (frame->har==har && frame->animation<animation) ||",
        "           (frame->har==har && frame->animation==animation && frame->sprite<sprite))",
        "            low=mid+1;",
        "        else high=mid;",
        "    }",
        "    if(low<sizeof(frames)/sizeof(frames[0]) && frames[low].har==har &&",
        "       frames[low].animation==animation && frames[low].sprite==sprite)",
        "        return &frames[low];",
        "    return NULL;",
        "}",
        "",
    ])
    return "\n".join(lines)


def warn_shared_sprites(rows: list[dict[str, str]], path: Path) -> None:
    """Warn about animations that draw the same sprites but have different explicit poses.

    Reads the groups written by sprite_duplicates.py (project/build/duplicate-sprites.json).
    """
    if not path.is_file():
        print("Shared sprites: not checked; run python project/tools/sprite_duplicates.py first")
        return
    authored = {(int(r["har"]), int(r["animation"]), int(r["sprite"])): r for r in rows}
    for group in json.loads(path.read_text(encoding="utf-8")):
        har = group["har"]
        members = [m for m in group["members"] if m["match"] == "identical"]
        done = [m["animation"] for m in members if any((har, m["animation"], s) in authored
                                                       for s in range(m["sprites"]))]
        for sprite in range(min(m["sprites"] for m in members) if members else 0):
            have = [(a, authored[(har, a, sprite)]) for a in done if (har, a, sprite) in authored]
            # Two rows only disagree where both define the same part (arm, leg, ...); a part that only
            # one of them has is not a conflict.
            for i, (a, first) in enumerate(have):
                for b, second in have[i + 1:]:
                    common = set(first["flags"].split("|")) & set(second["flags"].split("|"))
                    fields = [f for flag in common for f in FLAG_FIELDS[flag]]
                    if any(first[f] != second[f] for f in fields):
                        print(f"Shared sprites, HAR {har}: sprite {sprite} of animations {a} and {b} "
                              f"has different poses; check which is right")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=paths.DATA / "pose_catalog.csv")
    parser.add_argument("--output", type=Path, default=paths.PROTOTYPE / "pose_catalog.c")
    parser.add_argument("--inventory", type=Path, default=paths.ARTIFACTS / "pose-inventory.csv")
    parser.add_argument("--check", action="store_true", help="Fail if generated C is stale")
    args = parser.parse_args()
    authored_rows = read_rows(args.catalog)
    rows, shared = expand_shared(authored_rows, GROUPS)
    source = render(rows)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != source:
            parser.error(f"Generated pose catalog is stale: {args.output}")
    else:
        args.output.write_text(source, encoding="utf-8")
    print(f"Authored pose frames: {len(authored_rows)} (+{shared} shared through sprite groups)"
          if GROUPS.is_file() else
          f"Authored pose frames: {len(authored_rows)}; sprite groups not applied (run sprite_duplicates.py --write-groups)")
    if args.inventory.is_file():
        with args.inventory.open(newline="", encoding="utf-8") as stream:
            inventory = list(csv.DictReader(stream))
        sprite_keys = sum(int(move["sprites"]) for move in inventory)
        print(f"Coverage: {len(rows)} / {sprite_keys} animation sprite keys across {len(inventory)} moves")
    warn_shared_sprites(authored_rows, args.inventory.parent / "duplicate-sprites.json")


if __name__ == "__main__":
    main()
