"""Build prototype mesh data from the same editable Jaguar/Shadow sources."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "robots"))
from jaguar.blockout import build as jaguar  # noqa: E402
from shadow.blockout import build as shadow  # noqa: E402


def group(name: str) -> int:
    if name.startswith(("helmet", "rear_helmet", "eye_", "face_", "neck_")):
        return 1
    if name.startswith(("shoulder_joint", "upper_arm")):
        return 3
    if name.startswith(("elbow", "forearm")):
        return 4
    if name.startswith(("wrist", "palm", "hand", "finger", "thumb")):
        return 5
    if name.startswith(("hip_joint", "pelvis")):
        return 2
    if name.startswith(("thigh",)):
        return 6
    if name.startswith(("knee", "shin")):
        return 7
    if name.startswith(("ankle", "foot")):
        return 8
    return 0


def format_float(v: float) -> str:
    return f"{v:.6f}f"


def main():
    jaguar.PARTS.clear()
    jaguar.make_model()
    models = [(0, list(jaguar.PARTS))]
    jaguar.PARTS.clear()
    shadow.make_model()
    models.append((1, list(jaguar.PARTS)))
    positions = []
    indices = []
    parts = []
    for har, model in models:
        for name, vertices, faces, color in model:
            side = -1 if "_-1" in name else (1 if "_+1" in name else 0)
            vo, io = len(positions), len(indices)
            positions.extend(vertices)
            indices.extend(vo+i for tri in faces for i in tri)
            parts.append((har, name, group(name), side, io, len(faces)*3, color))
    lines = ["// Generated by generate_model_meshes.py. Edit the glTF blockout generators.",
             "#ifndef OMF3K_MODEL_MESHES_H", "#define OMF3K_MODEL_MESHES_H",
             "#include <stdint.h>",
             "typedef struct { float x,y,z; } ModelPosition;",
             "typedef struct { const char *name; int har, group, side; unsigned first, count; unsigned char r,g,b; } ModelPart;",
             "static const ModelPosition model_positions[] = {"]
    lines.extend("    {"+",".join(format_float(v) for v in p)+"}," for p in positions)
    lines.append("};")
    lines.append("static const uint16_t model_indices[] = {")
    for i in range(0, len(indices), 24):
        lines.append("    "+", ".join(str(n) for n in indices[i:i+24])+",")
    lines.append("};")
    lines.append("static const ModelPart model_parts[] = {")
    for har, name, rig_group, side, first, count, color in parts:
        lines.append(f'    {{"{name}", {har}, {rig_group}, {side}, {first}, {count}, '
                     f'{color[0]}, {color[1]}, {color[2]}}},')
    lines.extend(("};", "#endif"))
    out = ROOT / "prototype" / "model_meshes.h"
    out.write_text("\n".join(lines)+"\n")
    print(f"{len(parts)} parts, {len(positions)} vertices, {len(indices)//3} triangles")


if __name__ == "__main__":
    main()
